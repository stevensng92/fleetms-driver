// One list of what refreshes after any job change: the Jobs list, every open
// job or Trip screen, and Earnings. The four job actions and the live listener
// all use it, so no screen can be missed by one path and not the other.
import React from 'react';
import { renderHook, act } from '@testing-library/react-native';
import { QueryClient, QueryClientProvider, useQuery } from '@tanstack/react-query';

const mockRpc = jest.fn();
jest.mock('../../supabase', () => ({ supabase: { rpc: (...a: unknown[]) => mockRpc(...a) } }));

import {
  refreshJobs, useConfirmAssignment, useRejectAssignment, useStartJob, useCompleteJob,
} from '../jobActions';

// Every query that shows a job, seeded so the test can see which go stale.
const JOB_KEYS = [
  ['jobs', 'today', '24h'],
  ['job-by-number', 'JOB-001'],
  ['driver-earnings', 'this-month'],
  ['driver-earnings-history-start'],
];
const OTHER_KEYS = [['notifications', '24h'], ['driver-profile'], ['expenses']];

function seededClient() {
  // gcTime Infinity: no cleanup timers, so jest can exit.
  const qc = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: Infinity }, mutations: { gcTime: Infinity } } });
  for (const k of [...JOB_KEYS, ...OTHER_KEYS]) qc.setQueryData(k, 'x');
  return qc;
}
const stale = (qc: QueryClient, k: unknown[]) => qc.getQueryState(k)?.isInvalidated;

beforeEach(() => { mockRpc.mockReset(); mockRpc.mockResolvedValue({ data: null, error: null }); });

describe('refreshJobs', () => {
  it('marks every query that shows a job stale, and nothing else', async () => {
    const qc = seededClient();
    await refreshJobs(qc);
    for (const k of JOB_KEYS) expect(stale(qc, k)).toBe(true);
    for (const k of OTHER_KEYS) expect(stale(qc, k)).toBe(false);
  });
});

describe('job actions', () => {
  const cases: [string, () => any, unknown][] = [
    ['Accept', () => useConfirmAssignment(), 'asg-1'],
    ['Reject', () => useRejectAssignment(), { assignmentId: 'asg-1', reason: 'sick' }],
    ['Start', () => useStartJob(), 'job-uuid-1'],
    ['Complete', () => useCompleteJob(), 'job-uuid-1'],
  ];

  it.each(cases)('%s refreshes every screen that shows the job', async (_name, hook, arg) => {
    const qc = seededClient();
    const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
    const { result } = await renderHook(hook, { wrapper });
    await act(async () => { await result.current.mutateAsync(arg); });
    for (const k of JOB_KEYS) expect(stale(qc, k)).toBe(true);
    for (const k of OTHER_KEYS) expect(stale(qc, k)).toBe(false);
  });

  // Generated by /ship test coverage audit.
  // Value: protects=each action calls its own server function with the argument names the server expects; Reject with no reason sends null; fails_when=the shared useJobAction rewrite swaps an RPC name or param key (target_job_id vs target_assignment_id) or drops reason ?? null; why_new=the cases above only check the refresh, never what was sent; seam=none; no_claim=the real RPCs accept these args (mocked supabase.rpc; unit only)
  it.each([
    ['Accept', () => useConfirmAssignment(), 'asg-1', 'driver_confirm_assignment', { target_assignment_id: 'asg-1' }],
    ['Reject', () => useRejectAssignment(), { assignmentId: 'asg-1', reason: 'sick' }, 'driver_reject_assignment', { target_assignment_id: 'asg-1', reject_reason: 'sick' }],
    ['Reject with no reason', () => useRejectAssignment(), { assignmentId: 'asg-1' }, 'driver_reject_assignment', { target_assignment_id: 'asg-1', reject_reason: null }],
    ['Start', () => useStartJob(), 'job-uuid-1', 'driver_start_job', { target_job_id: 'job-uuid-1' }],
    ['Complete', () => useCompleteJob(), 'job-uuid-1', 'driver_complete_job', { target_job_id: 'job-uuid-1' }],
  ] as [string, () => any, unknown, string, object][])('%s calls the right server action with the right arguments', async (_name, hook, arg, rpc, params) => {
    const qc = seededClient();
    const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
    const { result } = await renderHook(hook, { wrapper });
    await act(async () => { await result.current.mutateAsync(arg); });
    expect(mockRpc).toHaveBeenCalledTimes(1);
    expect(mockRpc).toHaveBeenCalledWith(rpc, params);
  });

  // Value: protects=after a job action the open job screen shows the new status (e.g. the Trip screen after On my way), yet a hung reload never keeps the button spinning past 2 seconds; fails_when=the action stops waiting for the reload, or waits without a limit; why_new=no test timed the action against a slow or hung reload; seam=none; no_claim=real network timing
  it('waits for the job screen to reload before finishing', async () => {
    const qc = seededClient();
    const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
    let answer: (v: string) => void = () => {};
    const { result } = await renderHook(() => {
      useQuery({ queryKey: ['job-by-number', 'JOB-001'], queryFn: () => new Promise<string>(r => { answer = r; }), initialData: 'x', staleTime: Infinity });
      return useStartJob();
    }, { wrapper });
    let done = false;
    await act(async () => { void result.current.mutateAsync('job-uuid-1').then(() => { done = true; }); });
    await act(async () => { await Promise.resolve(); });
    expect(done).toBe(false);
    await act(async () => { answer('in progress'); });
    await act(async () => { await Promise.resolve(); await Promise.resolve(); });
    expect(done).toBe(true);
    expect(qc.getQueryData(['job-by-number', 'JOB-001'])).toBe('in progress');
  });

  it('stops waiting for a hung reload after 2 seconds', async () => {
    jest.useFakeTimers();
    try {
      const qc = seededClient();
      const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
      const { result } = await renderHook(() => {
        useQuery({ queryKey: ['job-by-number', 'JOB-001'], queryFn: () => new Promise(() => {}), initialData: 'x', staleTime: Infinity });
        return useCompleteJob();
      }, { wrapper });
      let done = false;
      await act(async () => { void result.current.mutateAsync('job-uuid-1').then(() => { done = true; }); });
      await act(async () => { await jest.advanceTimersByTimeAsync(1900); });
      expect(done).toBe(false);
      await act(async () => { await jest.advanceTimersByTimeAsync(200); });
      expect(done).toBe(true);
    } finally {
      jest.useRealTimers();
    }
  });

  it('refreshes nothing when the server refuses the action', async () => {
    mockRpc.mockResolvedValue({ data: null, error: { message: 'no' } });
    const qc = seededClient();
    const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
    const { result } = await renderHook(() => useStartJob(), { wrapper });
    await act(async () => { await expect(result.current.mutateAsync('job-uuid-1')).rejects.toBeTruthy(); });
    for (const k of JOB_KEYS) expect(stale(qc, k)).toBe(false);
  });
  // dispatch changed the job under the driver: the pop-up says "It's been updated on your screen", so it must be.
  it('refreshes every job screen when dispatch has changed the job, and still rejects', async () => {
    mockRpc.mockResolvedValue({ data: null, error: { message: 'Cannot start a pending job (must be confirmed)', code: 'P0001' } });
    const qc = seededClient();
    const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
    const { result } = await renderHook(() => useStartJob(), { wrapper });
    await act(async () => { await expect(result.current.mutateAsync('job-uuid-1')).rejects.toMatchObject({ code: 'P0001' }); });
    for (const k of JOB_KEYS) expect(stale(qc, k)).toBe(true);
    for (const k of OTHER_KEYS) expect(stale(qc, k)).toBe(false);
  });

  it('does not refresh when the failure is only a lost connection', async () => {
    mockRpc.mockRejectedValue(new TypeError('Network request failed'));
    const qc = seededClient();
    const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
    const { result } = await renderHook(() => useStartJob(), { wrapper });
    await act(async () => { await expect(result.current.mutateAsync('job-uuid-1')).rejects.toBeInstanceOf(TypeError); });
    for (const k of JOB_KEYS) expect(stale(qc, k)).toBe(false);
  });

  it('stops waiting for a hung reload after 2 seconds on a changed job too', async () => {
    jest.useFakeTimers();
    try {
      mockRpc.mockResolvedValue({ data: null, error: { message: 'No current assignment for job', code: 'P0001' } });
      const qc = seededClient();
      const wrapper = ({ children }: { children: React.ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
      const { result } = await renderHook(() => {
        useQuery({ queryKey: ['job-by-number', 'JOB-001'], queryFn: () => new Promise(() => {}), initialData: 'x', staleTime: Infinity });
        return useCompleteJob();
      }, { wrapper });
      let failed = false;
      await act(async () => { void result.current.mutateAsync('job-uuid-1').catch(() => { failed = true; }); });
      await act(async () => { await jest.advanceTimersByTimeAsync(1900); });
      expect(failed).toBe(false);
      await act(async () => { await jest.advanceTimersByTimeAsync(200); });
      expect(failed).toBe(true);
    } finally {
      jest.useRealTimers();
    }
  });
});
